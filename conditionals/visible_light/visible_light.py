n=int(input())
if n>=380 and n<450 :
    print("Violet")
elif n>=450 and n<495 :
    print("Blue")
elif n>=495 and n<570 :
    print("Green")
elif n>=570 and n<590 :
    print("Yellow")
elif n>=590 and n<620 :
    print("Orange")
elif n>=620 and n<=750 :
    print("Red")
else :
    print("Outside visible spectrum")