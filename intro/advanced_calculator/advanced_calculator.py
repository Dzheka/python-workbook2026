a = int(input())
b = int(input())
plus = (a + b)
minus = (a - b)
multiply = (a * b)
division = (a / b)
integer_division = (a // b)
module = (a % b)
power = (a ** b)

print(f'{a} + {b} = {plus}')
print(f'{a} - {b} = {minus}')
print(f'{a} * {b} = {multiply}')
print(f'{a} / {b} = {division:.2f}')
print(f'{a} // {b} = {integer_division}')
print(f'{a} % {b} = {module}')
print(f'{a} ** {b} = {power}')

