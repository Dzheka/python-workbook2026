a = float(input())
if a < 2.0:
    print("Micro")
elif a < 3.0:
    print("Very Minor")
elif a < 4.0:
    print("Minor")
elif a < 5.0:
    print("Light")
elif a < 6.0:
    print("Moderate")
elif a < 7.0:
    print("Strong")
elif a < 8.0:
    print("Major")
elif a < 10.0:
    print("Great")
else:
    print("Meteoric")